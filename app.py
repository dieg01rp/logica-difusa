# logica difusa - mamdani
resolucion = 1000
u_urgencia = np.linspace(0, 10, resolucion)
u_retraso = np.linspace(0, 72, resolucion)
u_importancia = np.linspace(0, 100, resolucion)
u_prioridad = np.linspace(0, 100, resolucion)

def trimf(x, abc):
    a, b, c = map(float, abc)
    with np.errstate(divide='ignore', invalid='ignore'):
        term1 = (x - a) / (b - a)
        term2 = (c - x) / (c - b)
    resultado = np.minimum(term1, term2)
    if b == a: resultado = np.where(x == b, 1.0, resultado)
    return np.clip(resultado, 0.0, 1.0)

def trapmf(x, abcd):
    a, b, c, d = map(float, abcd)
    with np.errstate(divide='ignore', invalid='ignore'):
        term1 = (x - a) / (b - a) if b > a else np.where(x >= a, 1.0, 0.0)
        term2 = (d - x) / (d - c) if d > c else np.where(x <= d, 1.0, 0.0)
    resultado = np.minimum(np.minimum(term1, 1.0), term2)
    resultado = np.where((x >= b) & (x <= c), 1.0, resultado)
    return np.clip(resultado, 0.0, 1.0)

particiones = {
    'urgencia': {
        'baja': trapmf(u_urgencia, [0, 0, 2, 4]),
        'media': trimf(u_urgencia, [2, 5, 8]),
        'alta': trapmf(u_urgencia, [6, 8, 10, 10])
    },
    'retraso': {
        'bajo': trapmf(u_retraso, [0, 0, 12, 24]),
        'medio': trimf(u_retraso, [18, 36, 54]),
        'alto': trapmf(u_retraso, [48, 60, 72, 72])
    },
    'importancia': {
        'baja': trapmf(u_importancia, [0, 0, 25, 45]),
        'media': trimf(u_importancia, [35, 50, 65]),
        'alta': trapmf(u_importancia, [55, 75, 100, 100])
    },
    'prioridad': {
        'baja': trapmf(u_prioridad, [0, 0, 20, 40]),
        'media': trimf(u_prioridad, [30, 50, 70]),
        'critica': trapmf(u_prioridad, [60, 80, 100, 100])
    }
}

def evaluar_sistema_difuso(urg, ret, imp):
    mu_urg = {k: np.interp(urg, u_urgencia, v) for k, v in particiones['urgencia'].items()}
    mu_ret = {k: np.interp(ret, u_retraso, v) for k, v in particiones['retraso'].items()}
    mu_imp = {k: np.interp(imp, u_importancia, v) for k, v in particiones['importancia'].items()}

    reglas = [
        (np.minimum(np.minimum(mu_urg['baja'], mu_ret['bajo']), mu_imp['baja']), 'baja'),
        (np.minimum(np.minimum(mu_urg['alta'], mu_ret['alto']), mu_imp['alta']), 'critica'),
        (np.minimum(np.minimum(mu_urg['media'], mu_ret['medio']), mu_imp['media']), 'media'),
        (np.minimum(np.minimum(mu_urg['baja'], mu_ret['alto']), mu_imp['alta']), 'critica'),
        (np.minimum(np.minimum(mu_urg['alta'], mu_ret['bajo']), mu_imp['baja']), 'media'),
        (np.minimum(np.minimum(mu_urg['media'], mu_ret['alto']), mu_imp['baja']), 'media'),
        (np.minimum(np.minimum(mu_urg['alta'], mu_ret['medio']), mu_imp['alta']), 'critica'),
        (np.minimum(np.minimum(mu_urg['baja'], mu_ret['bajo']), mu_imp['alta']), 'media'),
        (np.minimum(np.minimum(mu_urg['media'], mu_ret['bajo']), mu_imp['alta']), 'media'),
        (np.minimum(np.minimum(mu_urg['baja'], mu_ret['alto']), mu_imp['baja']), 'baja')
    ]

    curva_agregada = np.zeros_like(u_prioridad)
    for peso_regla, etiqueta_salida in reglas:
        curva_implicada = np.minimum(peso_regla, particiones['prioridad'][etiqueta_salida])
        curva_agregada = np.maximum(curva_agregada, curva_implicada)

    suma_mu = np.sum(curva_agregada)
    centroide = np.sum(u_prioridad * curva_agregada) / suma_mu if suma_mu > 0 else 50.0
    return centroide, curva_agregada

# algoritmo genetico
proyectos_costos = np.array([6500, 2800, 1800, 4500, 7000, 3200, 5000, 2200], dtype=np.float64)
proyectos_beneficios = np.array([18, 8, 6, 12, 19, 10, 14, 7], dtype=np.float64)
PRESUPUESTO_MAX = 17000.0

def calcular_fitness(cromosoma):
    costo_total = np.sum(cromosoma * proyectos_costos)
    if costo_total > PRESUPUESTO_MAX: return 0.0
    return float(np.sum(cromosoma * proyectos_beneficios))

def ejecutar_ag(pop_size, pc, pm, max_gen, seed):
    np.random.seed(seed)
    n_genes = 8
    poblacion = np.random.randint(0, 2, size=(pop_size, n_genes))
    historial_mejor = []

    for gen in range(max_gen):
        fitness = np.array([calcular_fitness(ind) for ind in poblacion])
        idx_mejor = np.argmax(fitness)
        elite_ind = poblacion[idx_mejor].copy()
        elite_fit = fitness[idx_mejor]
        historial_mejor.append(elite_fit)

        nueva_pob = []
        while len(nueva_pob) < pop_size:
            idx1, idx2 = np.random.choice(pop_size, size=2, replace=False)
            p1 = poblacion[idx1] if fitness[idx1] >= fitness[idx2] else poblacion[idx2]
            idx3, idx4 = np.random.choice(pop_size, size=2, replace=False)
            p2 = poblacion[idx3] if fitness[idx3] >= fitness[idx4] else poblacion[idx4]

            if np.random.rand() <= pc:
                punto = np.random.randint(1, n_genes)
                h1 = np.concatenate([p1[:punto], p2[punto:]])
                h2 = np.concatenate([p2[:punto], p1[punto:]])
            else:
                h1, h2 = p1.copy(), p2.copy()

            for i in range(n_genes):
                if np.random.rand() < pm: h1[i] = 1 - h1[i]
                if np.random.rand() < pm: h2[i] = 1 - h2[i]

            nueva_pob.extend([h1, h2])

        poblacion = np.array(nueva_pob[:pop_size])
        poblacion[0] = elite_ind

    fitness_final = np.array([calcular_fitness(ind) for ind in poblacion])
    idx_optimo = np.argmax(fitness_final)
    return poblacion[idx_optimo], fitness_final[idx_optimo], historial_mejor

